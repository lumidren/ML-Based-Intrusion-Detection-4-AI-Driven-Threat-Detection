"""Measured dataset statistics for the data card (``nids data profile``)."""

from __future__ import annotations

import json
import re
from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Any

import polars as pl

from nids.data import cleaning
from nids.data.loaders import canonical_path, day_path, iter_day_files
from nids.data.schema import DAYS, FLOW_FEATURES, DayInfo

BEGIN = "<!-- BEGIN MEASURED (generated by `nids data profile`; do not edit by hand) -->"
END = "<!-- END MEASURED -->"


def _day_stats(lf: pl.LazyFrame) -> tuple[dict[str, Any], pl.DataFrame, pl.DataFrame]:
    """Streaming aggregates for one day: totals and feature ranges, labels, per-port counts."""
    totals = (
        lf.select(
            pl.len().alias("rows"),
            pl.col("is_attack").sum().alias("attack_rows"),
            *[pl.col(f).min().alias(f"min_{f}") for f in FLOW_FEATURES],
            *[pl.col(f).max().alias(f"max_{f}") for f in FLOW_FEATURES],
        )
        .collect(engine="streaming")
        .row(0, named=True)
    )
    labels = lf.group_by("label").len().sort("label").collect(engine="streaming")
    ports = (
        lf.group_by("dst_port")
        .agg(pl.col("is_attack").sum().alias("attack_rows"), pl.len().alias("total"))
        .collect(engine="streaming")
    )
    return totals, labels, ports


def profile_days(
    items: Iterable[tuple[str, str, pl.LazyFrame, cleaning.CleaningReport]],
) -> dict[str, Any]:
    """Compute data-card statistics one day at a time.

    ``items`` yields (dataset, day, canonical lazy frame, cleaning report) per day. Only one
    day's aggregates are in memory at any time.
    """
    out: dict[str, Any] = {"rows": 0, "datasets": {}}
    acc: dict[str, dict[str, Any]] = {}
    for ds, day, lf, rep in items:
        totals, labels, ports = _day_stats(lf)
        info = next((d for d in DAYS if d.day == day), None)
        a = acc.setdefault(
            ds, {"rows": 0, "attack_rows": 0, "mins": {}, "maxs": {}, "ports": [], "days": []}
        )
        rows, attacks = int(totals["rows"]), int(totals["attack_rows"] or 0)
        a["rows"] += rows
        a["attack_rows"] += attacks
        for f in FLOW_FEATURES:
            lo, hi = totals[f"min_{f}"], totals[f"max_{f}"]
            a["mins"][f] = lo if f not in a["mins"] else min(a["mins"][f], lo)
            a["maxs"][f] = hi if f not in a["maxs"] else max(a["maxs"][f], hi)
        a["ports"].append(ports)
        a["days"].append(
            {
                "day": day,
                "rows": rows,
                "expected_rows": info.expected_rows if info else None,
                "attack_rows": attacks,
                "labels": {str(k): int(v) for k, v in labels.iter_rows()},
                "inf_rows": rep.inf_replaced,
                "negative_duration": rep.negative_duration_dropped,
                "duplicates": rep.duplicates_dropped,
                "duplicate_frac": round(rep.duplicates_dropped / max(rows, 1), 4),
                "rows_after_clean": rep.rows_out,
                "label_reliable": bool(info.label_reliable) if info else True,
            }
        )
    for ds, a in acc.items():
        out["rows"] += a["rows"]
        per_port = (
            pl.concat(a["ports"])
            .group_by("dst_port")
            .agg(pl.col("attack_rows").sum(), pl.col("total").sum())
            .with_columns(attack_share=pl.col("attack_rows") / pl.col("total"))
            .sort(["attack_rows", "dst_port"], descending=[True, False])
            .head(5)
        )
        out["datasets"][ds] = {
            "rows": a["rows"],
            "attack_rows": a["attack_rows"],
            "attack_frac": round(a["attack_rows"] / max(a["rows"], 1), 4),
            "constant_features": [f for f in FLOW_FEATURES if a["mins"][f] == a["maxs"][f]],
            "top_attack_ports": [
                {
                    "port": int(r["dst_port"]),
                    "attack_rows": int(r["attack_rows"]),
                    "total_rows": int(r["total"]),
                    "attack_share": round(float(r["attack_share"]), 4),
                }
                for r in per_port.iter_rows(named=True)
            ],
            "days": a["days"],
        }
    return out


def profile(df: pl.DataFrame) -> dict[str, Any]:
    """Profile an in-memory canonical frame (tests and small samples)."""

    def items() -> Iterator[tuple[str, str, pl.LazyFrame, cleaning.CleaningReport]]:
        for (ds, day), g in df.group_by(["dataset", "day"], maintain_order=True):
            _, rep = cleaning.clean(g)
            yield str(ds), str(day), g.lazy(), rep

    return profile_days(items())


def profile_dir(processed_root: Path) -> dict[str, Any]:
    """Profile every canonical day file, cleaning (streamed) any day not cleaned yet."""

    def items() -> Iterator[tuple[str, str, pl.LazyFrame, cleaning.CleaningReport]]:
        for day, path in iter_day_files(processed_root, "canonical"):
            rep = clean_day(day, processed_root)
            yield day.dataset.value, day.day, pl.scan_parquet(path), rep

    return profile_days(items())


def clean_day(day: DayInfo, processed_root: Path, force: bool = False) -> cleaning.CleaningReport:
    """Stream-clean one canonical day into the ``clean`` stage; cache the report next to it."""
    dst = day_path(day, processed_root, "clean")
    report = dst.with_suffix(".report.json")
    if report.exists() and dst.exists() and not force:
        return cleaning.CleaningReport(**json.loads(report.read_text()))
    rep = cleaning.clean_file(canonical_path(day, processed_root), dst)
    report.write_text(json.dumps(rep.as_dict(), indent=2))
    return rep


def to_markdown(p: dict[str, Any]) -> str:
    lines = [f"Total canonical rows: **{p['rows']:,}**", ""]
    for ds, d in p["datasets"].items():
        lines += [
            f"### {ds}",
            "",
            f"Rows: {d['rows']:,}; attack rows: {d['attack_rows']:,} ({d['attack_frac']:.1%}).",
            "",
            "Most-attacked destination ports with the attack share of all flows on that port "
            "(the raw port is a label proxy, so the model only sees a 3-level bucket):",
            "",
            "| Port | Attack rows | All rows | Attack share |",
            "|---:|---:|---:|---:|",
            *[
                f"| {p['port']} | {p['attack_rows']:,} | {p['total_rows']:,} | {p['attack_share']:.1%} |"
                for p in d["top_attack_ports"]
            ],
            "",
            f"Constant features in this dataset: {', '.join(d['constant_features']) or 'none'}.",
            "",
            "| Day | Rows | Published | Attack rows | inf rows | Negative duration | Exact duplicates | After clean | Labels reliable |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---|",
        ]
        for day in d["days"]:
            pub = f"{day['expected_rows']:,}" if day["expected_rows"] else "-"
            lines.append(
                f"| {day['day']} | {day['rows']:,} | {pub} | {day['attack_rows']:,} | {day['inf_rows']:,} | "
                f"{day['negative_duration']:,} | {day['duplicates']:,} ({day['duplicate_frac']:.1%}) | "
                f"{day['rows_after_clean']:,} | {'yes' if day['label_reliable'] else 'no'} |"
            )
        lines += ["", "Label counts per day:", ""]
        for day in d["days"]:
            labs = ", ".join(f"{k}: {v:,}" for k, v in day["labels"].items())
            lines.append(f"* `{day['day']}` - {labs}")
        lines.append("")
    return "\n".join(lines)


def update_data_card(card: Path, p: dict[str, Any], json_out: Path | None = None) -> None:
    text = card.read_text(encoding="utf-8")
    block = f"{BEGIN}\n{to_markdown(p)}\n{END}"
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    card.write_text(new, encoding="utf-8")
    if json_out:
        json_out.parent.mkdir(parents=True, exist_ok=True)
        json_out.write_text(json.dumps(p, indent=2, default=str))
